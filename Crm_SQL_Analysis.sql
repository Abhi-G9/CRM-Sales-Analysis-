-- Data Modeling

CREATE VIEW crm_sales_model AS
SELECT
    sp.opportunity_id,
    sp.deal_stage,
    sp.engage_date,
    sp.close_date,
    sp.close_value,

    a.account,
    a.sector,
    a.revenue AS company_revenue,
    a.employees,
    a.office_location,

    p.product,
    p.series,
    p.sales_price,

    st.sales_agent,
    st.manager,
    st.regional_office

FROM sales_pipeline sp

LEFT JOIN accounts a
ON sp.account = a.account

LEFT JOIN products p
ON sp.product = p.product

LEFT JOIN sales_teams st
ON sp.sales_agent = st.sales_agent;


