-- Q6: On average, how many days did it take to win deals?

 with Diff as (
    select deal_stage,
           datediff(close_date, engage_date) as Complete_Deal_Time
    from crm_sales_model
)
select deal_stage, avg(Complete_Deal_Time) as Avg_Won_Time
from Diff
where deal_stage = 'Won'
group by deal_stage;
  
