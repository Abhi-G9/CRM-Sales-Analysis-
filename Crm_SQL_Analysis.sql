 -- Q14: For each industry sector, what is the total number of won/lost deals and the average time taken to close them?

  
SELECT 
    sector,
    SUM(CASE WHEN deal_stage = 'Lost' THEN 1 ELSE 0 END) AS Lost_Deals,
    SUM(CASE WHEN deal_stage = 'Won' THEN 1 ELSE 0 END) AS Won_Deals,
    COUNT(*) AS Total_Deals,
    ROUND(AVG(CASE WHEN deal_stage = 'Lost' THEN DATEDIFF(close_date, engage_date) END),2) AS Avg_Lost_Time,
    ROUND(AVG(CASE WHEN deal_stage = 'Won' THEN DATEDIFF(close_date, engage_date) END),2) AS Avg_Won_Time
FROM crm_sales_model
WHERE deal_stage IN ('Lost','Won')
GROUP BY sector;

