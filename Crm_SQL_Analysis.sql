-- Q1: What is the total revenue generated by each account(Company)?
select `account`,sum(company_revenue)as Total_Revenue  from crm_sales_model group by `account`;

-- Q2: How many deals were lost for each product?
select `product`, `deal_stage`,count(*) as Deal_count from  crm_sales_model where deal_stage = 'Lost' group by `product` ,`deal_stage`;

-- Q3: How many deals were won for each product?
select `product`, `deal_stage`,count(*) as Deal_count from  crm_sales_model where deal_stage = 'Won' group by `product` ,`deal_stage`;


