  -- Q10: How many deals were won by each sales agent?
 select sales_agent , count(*) as agent_Won_deal from crm_sales_model where deal_stage='Won' group by sales_agent;


-- Q11: For each sales agent, what is the average, fastest, and slowest closing time, and how many deals did they win?

  with Diff as (
    select sales_agent,
           deal_stage,
           datediff(close_date, engage_date) as Complete_Deal_Time
    from crm_sales_model
    where deal_stage = 'Won'
)
select sales_agent,
       avg(Complete_Deal_Time) as Avg_Closing_Days,
       min(Complete_Deal_Time) as Fastest_Deal,
       max(Complete_Deal_Time) as Slowest_Deal,
       count(*) as Total_Won_Deals
from Diff
group by sales_agent
order by Avg_Closing_Days asc ;

